// ============================================================
// Сумма накладной — ОДНА точка чтения.
//
// ЗАЧЕМ. Сумма живёт в ДВУХ местах: колонка Request.totalSum и поле
// details.totalSum внутри JSON. Так сложилось исторически, и на проде есть
// 40 частных накладных (созданы с 20.04 по 12.08.2026), у которых колонка
// ПУСТАЯ, а сумма лежит только в details.
//
// Карточка накладной читала с запасным вариантом (`data.totalSum ||
// details.totalSum`) и сумму показывала, а списки читали голую колонку —
// и показывали «—». Один и тот же документ выглядел по-разному снаружи и
// внутри, причём снаружи — беднее.
//
// Правка колонки в базе отдельным скриптом (scripts/backfill-total-sum.mjs)
// эту проблему снимает для СУЩЕСТВУЮЩИХ записей, но код всё равно обязан
// уметь читать оба места: скрипт разово чинит данные, а защита от повторения
// нужна постоянная.
//
// ПОЧЕМУ ОБЩИЙ МОДУЛЬ, А НЕ ФОЛБЭК В КАЖДОМ СПИСКЕ. Мест чтения семь
// (Бухгалтерия, Отработанные, Заявки, ТТН, СМР, Отложенные, карточка), и в
// каждом сумма читается ТРИЖДЫ: для ячейки, для сортировки и для итога. Двадцать
// с лишним копий одного выражения разъедутся на первой же правке, и тогда в
// таблице будет одно число, в «Итого» другое, а сортировка — по третьему.
// ============================================================

/** details приходит то строкой JSON, то уже объектом — принимаем оба вида. */
function parseDetails(raw) {
  if (!raw) return {};
  if (typeof raw === 'object') return raw;
  try {
    const parsed = JSON.parse(String(raw));
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

/**
 * Число или null.
 *
 * Пустая строка, null и «не число» — это ОТСУТСТВИЕ суммы, а не ноль.
 * Ноль же — полноценное значение: накладная на 0 тг встречается (перевозка
 * за счёт другой), и показывать её как «сумма не указана» неверно.
 */
function toSum(value) {
  if (value === null || value === undefined) return null;
  const raw = String(value).trim();
  if (raw === '') return null;
  const n = Number(raw.replace(/\s+/g, '').replace(',', '.'));
  return Number.isFinite(n) ? n : null;
}

/**
 * Сумма накладной: колонка, иначе details.
 *
 * Порядок именно такой. Колонка — то, что пишет сегодняшний сервер
 * (createRequest: `totalSum ? String(totalSum) : ''`), и она главнее.
 * В details заглядываем, только если колонка пуста.
 *
 * @returns {number|null} null — суммы нет нигде.
 */
export function actTotalSum(act) {
  if (!act || typeof act !== 'object') return null;

  const fromColumn = toSum(act.totalSum);
  if (fromColumn !== null) return fromColumn;

  return toSum(parseDetails(act.details).totalSum);
}

/**
 * Готовая подпись для ячейки таблицы: «12 300 тг» или «—».
 *
 * Форматирование здесь, а не на местах: иначе одна таблица покажет
 * «12300», другая «12 300», третья с «тг» — так и было до этого модуля.
 */
export function actSumText(act, suffix = '') {
  const sum = actTotalSum(act);
  if (sum === null) return '—';
  // Локаль НЕ форсируем: во всех таблицах до этого стоял голый
  // toLocaleString(), и жёсткое 'ru-RU' сменило бы разделитель разрядов
  // на неразрывный пробел — формат чисел поехал бы во всём приложении.
  return `${sum.toLocaleString()}${suffix}`;
}

/** Сумма для сортировки и итогов: отсутствие — ноль, иначе сравнивать нечем. */
export function actSumOrZero(act) {
  return actTotalSum(act) ?? 0;
}
