// ============================================================
// Доп. сумма за нестандартный груз (частные лица).
//
// ЗАЧЕМ. Иногда груз не считается по тарифу нормально — полкуба, нестандартная
// упаковка, разовая договорённость. Менеджеру нужно добавить сумму сверху.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ СЛАГАЕМЫМ, А НЕ ПРАВКОЙ ИТОГА. Перебить итог руками можно
// было и раньше, но такая правка не переживает пересчёта: стоит тронуть вес или
// город — движок пишет в поле свою сумму, и введённое пропадает. Доплата,
// живущая отдельно, переживает пересчёт: тариф меняется сам по себе, доплата
// стоит на месте, итог складывается из двух слагаемых.
//
// ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не трогает движок тарифов: доплата к расчёту
// отношения не имеет, она прибавляется ПОСЛЕ него. И не меняет смысл totalSum —
// там как был, так и остаётся ИТОГ (его читают список, чек, наклейка, отчёты).
// ============================================================

/** Число из поля ввода. Пустое, мусор и отрицательное — это ноль. */
function toAmount(v) {
  const n = parseFloat(v);
  if (!isFinite(n) || n <= 0) return 0;
  // До копеек: поле числовое, но вставить туда могут что угодно.
  return Math.round((n + Number.EPSILON) * 100) / 100;
}

/**
 * Читает доплату из сохранённых данных (details или уже разобранного act).
 *
 * Галочка отдельно не хранится: она выводится из самой суммы. Иначе появилось бы
 * второе состояние («галочка стоит, сумма пустая»), которое пришлось бы
 * согласовывать при каждой правке, и рано или поздно они разошлись бы.
 *
 * @returns {{ on: boolean, sum: number, note: string }}
 */
export function readExtra(source) {
  const s = source || {};
  const sum = toAmount(s.extraSum);
  return {
    on: sum > 0,
    sum,
    note: sum > 0 ? String(s.extraSumNote || "").trim() : "",
  };
}

/**
 * Поля для сохранения. Выключенная доплата пишется нулём, а не удаляется:
 * details на бэке СЛИВАЮТСЯ с прежними, и пропущенный ключ означал бы
 * «оставить как было» — снятая галочка не сохранилась бы.
 */
export function extraPatch({ on, sum, note } = {}) {
  const amount = on ? toAmount(sum) : 0;
  return {
    extraSum: amount,
    extraSumNote: amount > 0 ? String(note || "").trim() : "",
  };
}

/** Итог = тарифная часть + доплата. Единственное место, где они складываются. */
export function totalWithExtra(tariffSum, extra) {
  const base = parseFloat(tariffSum);
  const b = isFinite(base) ? base : 0;
  const e = extra && extra.on ? toAmount(extra.sum) : 0;
  return Math.round((b + e + Number.EPSILON) * 100) / 100;
}

/**
 * Тарифная часть итога — итог минус доплата.
 *
 * Нужна там, где есть только сохранённый итог: чек и карточка показывают
 * «тариф / доплата / итого», а тариф отдельно нигде не хранится. Пересчитывать
 * его движком нельзя — тарифы с тех пор могли поменяться, и в чеке получилось
 * бы одно, а в накладной другое.
 */
export function tariffPartOf(totalSum, extra) {
  const total = parseFloat(totalSum);
  const t = isFinite(total) ? total : 0;
  const e = extra && extra.on ? toAmount(extra.sum) : 0;
  return Math.round((t - e + Number.EPSILON) * 100) / 100;
}
