// ============================================================
// Формат номера накладной для показа и печати.
//
// ТЗ: нумерация частных идёт голым числом (1, 2, 3), а заказчик хочет видеть
// шесть знаков с ведущими нулями — 000001, 000002, 000042.
//
// ФОРМАТ ТОЛЬКО ПРИ ОТОБРАЖЕНИИ. В базе номер остаётся голым числом, и это
// осознанно:
//   • не нужна миграция уже выписанных накладных;
//   • выдача следующего номера на сервере считает MAX(CAST(docNumber AS BIGINT))
//     по маске '^[0-9]+$' — она продолжает работать без правок;
//   • откат — это откат кода, данные трогать не придётся.
//
// СТАРЫЕ ФОРМАТЫ НЕ ТРОГАЕМ. Номера вроде А000001 или IPT000005 — это другая,
// прежняя серия. Дополнять их нулями нельзя: получится документ с номером,
// которого нет ни в одной бумаге.
// ============================================================

export const DOC_NUMBER_WIDTH = 6;

/** Голое число — только цифры, без букв, префиксов и разделителей. */
export function isPlainNumber(value) {
  return /^\d+$/.test(String(value == null ? "" : value).trim());
}

/**
 * Номер для показа: голое число дополняется нулями слева до шести знаков,
 * любой другой формат возвращается как есть.
 *
 *   "42"        → "000042"
 *   "000042"    → "000042"   (уже дополнен — не меняем)
 *   "1234567"   → "1234567"  (длиннее шести — не режем, номер важнее формата)
 *   "А000001"   → "А000001"
 *   ""/null     → ""
 */
export function formatDocNumber(value) {
  const s = String(value == null ? "" : value).trim();
  if (!s) return "";
  if (!isPlainNumber(s)) return s;
  return s.padStart(DOC_NUMBER_WIDTH, "0");
}

/**
 * Номер для ПОИСКА. Обратная операция: снимает ведущие нули у голого числа,
 * чтобы введённое «000042» нашло сохранённое «42».
 *
 * Нужна, потому что печатаем мы дополненный номер, а храним голый: без этого
 * первая же попытка найти накладную по напечатанной наклейке провалилась бы.
 *
 *   "000042" → "42"     "42" → "42"     "000000" → "0"     "А000001" → "А000001"
 */
export function normalizeDocNumber(value) {
  const s = String(value == null ? "" : value).trim();
  if (!s || !isPlainNumber(s)) return s;
  const stripped = s.replace(/^0+/, "");
  return stripped === "" ? "0" : stripped;
}

/**
 * Варианты написания одного номера — для поиска по базе, где часть записей
 * могла быть сохранена уже дополненной.
 */
export function docNumberVariants(value) {
  const s = String(value == null ? "" : value).trim();
  if (!s) return [];
  if (!isPlainNumber(s)) return [s];
  const plain = normalizeDocNumber(s);
  const padded = formatDocNumber(plain);
  return plain === padded ? [plain] : [plain, padded];
}
