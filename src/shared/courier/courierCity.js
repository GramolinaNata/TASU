// Доступ курьера по городу.
//
// ТЗ: курьеру назначают город в «Персонале», и он видит только заявки своего
// города. Фильтр продублирован на сервере (request.controller.getRequests):
// скрытая строка в таблице ограничением не является — без серверной проверки
// курьер получил бы все заявки простым запросом к API.
//
// ⚠️ ПРИ ПРАВКЕ МЕНЯТЬ В ДВУХ МЕСТАХ: здесь и в server/src/controllers/
// request.controller.ts (функция requestCityForCourier). Общий модуль сделать
// нельзя — сборка бэка идёт из каталога server/ и до src/ не достаёт.

/**
 * Какой город заявки считается «городом курьера».
 *
 * 'toCity'   — куда доставляют (город назначения);
 * 'fromCity' — откуда забирают (город отправителя).
 *
 * Заказчик пока указал город назначения. Вопрос не окончательный: у курьера на
 * ОДНОЙ заявке есть и «Забрал», и «Доставил», то есть он ведёт её целиком —
 * если он работает в городе отправителя, правильным будет 'fromCity'.
 * Переключается этой одной строкой (и такой же в контроллере).
 */
export const COURIER_CITY_FIELD = 'toCity';

/** Приведение города к сравнимому виду: регистр и пробелы вводят как попало. */
export function normalizeCity(value) {
  return String(value || '').trim().toLowerCase();
}

/** Город заявки, по которому её видит курьер. */
export function requestCityForCourier(act) {
  const route = act?.route;
  // route бывает объектом (details.route) и склеенной строкой из колонки —
  // строку не разбираем, у всех заявок есть структурный вид.
  if (route && typeof route === 'object') return route[COURIER_CITY_FIELD] || '';
  return '';
}

/**
 * Виден ли курьеру этот документ.
 * Город не назначен → НИЧЕГО не видно: пустое поле означает «доступ не
 * настроен», а не «доступ ко всему». Иначе новый курьер до настройки видел бы
 * всю базу — ровно та дыра, которую закрываем.
 */
export function isVisibleToCourier(act, courierCity) {
  const city = normalizeCity(courierCity);
  if (!city) return false;
  return normalizeCity(requestCityForCourier(act)) === city;
}
