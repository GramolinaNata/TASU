// ============================================================
// Экспорт ТТН в официальный бланк (Приложение 9 к Правилам перевозок
// грузов автомобильным транспортом).
//
// Шаблон: public/templates/ttn_2026.xlsx — присланный заказчиком бланк,
// из которого вычищены данные образца и расставлены токены {ключ}.
//
// ПОЧЕМУ ExcelJS, А НЕ SheetJS. Прежняя версия читала и писала шаблон через
// SheetJS (xlsx). Community-сборка не пишет обратно оформление: на записи
// терялись рамки (58 определений → 1), шрифты, ссылки на стили у 1350 ячеек
// и весь блок pageSetup (A4, альбом). Госформа выезжала голой сеткой в
// книжной ориентации. ExcelJS переносит стили и параметры печати из шаблона
// один в один — проверено сравнением styles.xml до и после записи.
//
// exceljs грузится динамическим import() — библиотека тяжёлая (~1 МБ),
// и в основной чанк её тянуть незачем: ТТН выгружают редко.
// ============================================================

// file-saver подключается динамически вместе с exceljs: тогда у модуля нет
// браузерных зависимостей на верхнем уровне и buildTtnData можно импортировать
// в Node — например, из теста или скрипта проверки бланка.

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

// Имя стороны: у юрлица — компания, у частника — ФИО.
function partyName(party) {
  if (!party) return "";
  return party.companyName || party.fio || "";
}

// Адрес пункта: «улица, город». Пустые части выкидываем, чтобы не
// оставлять висячих запятых, когда адрес не заполнен.
function joinAddress(addr, city) {
  return [addr, city].map(s => String(s || "").trim()).filter(Boolean).join(", ");
}

// ── Данные для бланка ───────────────────────────────────────
// Ключи совпадают с токенами {ключ} внутри ttn_2026.xlsx.
// Единицы измерения («мест», «кг») входят в значение — так в бланке
// заказчика: в самих ячейках K32/W32 стоит «1 мест» и «142 кг».
export function buildTtnData(act) {
  const a = act || {};

  const d = a.date ? new Date(a.date) : null;
  const validDate = d && !isNaN(d.getTime());

  // Грузоотправитель. Форма заявки пишет sender = null, когда отправитель
  // совпадает с заказчиком (флаг isSenderSameAsCustomer, по умолчанию true).
  // В реальных данных флаг у большинства заявок вообще не сохранён, поэтому
  // ориентируемся на факт: есть отдельный отправитель — берём его, нет —
  // подставляем заказчика. Иначе графа «Грузоотправитель» в госформе
  // осталась бы пустой почти везде.
  const sender = partyName(a.sender) ? a.sender : a.customer;

  const seats = Number(a.totals?.seats) || 0;
  const weight = Number(a.totals?.weight) || 0;

  // Контакт получателя: «ФИО / телефон». Если чего-то нет — без разделителя.
  const receiverContact = [partyName(a.receiver), a.receiver?.phone]
    .map(s => String(s || "").trim()).filter(Boolean).join(" / ");

  return {
    number: a.docNumber || a.number || "",
    day: validDate ? String(d.getDate()) : "",
    month_year: validDate ? `${MONTHS[d.getMonth()]} ${d.getFullYear()} г.` : "",

    // «Автопредприятие» — компания-экспедитор, из которой выписана заявка
    // (согласовано с заказчиком). Перевозчик из справочника Carrier сюда
    // не подходит: он назначается на уровне партии, а не заявки.
    carrier_company: a.company?.name || "",

    customer: partyName(a.customer),
    sender: partyName(sender),
    receiver: partyName(a.receiver),

    loading_address: joinAddress(a.route?.fromAddress, a.route?.fromCity),
    unloading_address: joinAddress(a.route?.toAddress, a.route?.toCity),
    receiver_contact: receiverContact,

    cargo: a.cargoText || "",
    seats: seats ? `${seats} мест` : "",
    weight: weight ? `${weight} кг` : "",

    // «Масса брутто прописью»: по решению заказчика дублируем цифрами —
    // ровно так заполнен его собственный образец бланка.
    weight_words: weight ? `${weight} кг` : "",

    // ТЗ: данные автотранспорта в бланк. Раньше в шаблоне для них не было
    // токенов вовсе — графы «Автомобиль» и «Водитель» печатались пустыми,
    // и менеджер вписывал их от руки. Сами данные лежат в details.docAttrs
    // (марка, госномер, водитель, телефон) и с недавних пор обязательны
    // при формировании ТТН.
    //
    // Марка и госномер идут в одну графу: в бланке «Автомобиль» — одна
    // строка, отдельной ячейки под номер нет.
    vehicle: [a.docAttrs?.vehicleModel, a.docAttrs?.vehicleNumber]
      .map(s => String(s || "").trim()).filter(Boolean).join(" "),
    vehicle_model: String(a.docAttrs?.vehicleModel || "").trim(),
    vehicle_number: String(a.docAttrs?.vehicleNumber || "").trim(),

    // Водитель: ФИО и телефон вместе. Телефон в накладной заказчик просил
    // НЕ показывать, поэтому в графу «Водитель» идёт только ФИО, а телефон
    // отдаётся отдельным токеном — на случай, если понадобится позже.
    driver: String(a.docAttrs?.driver || "").trim(),
    driver_phone: String(a.docAttrs?.driverPhone || "").trim(),

    // Прицеп — если отмечен.
    trailer: a.docAttrs?.hasTrailer
      ? [a.docAttrs?.trailerModel, a.docAttrs?.trailerNumber]
          .map(s => String(s || "").trim()).filter(Boolean).join(" ")
      : "",
  };
}

// Подстановка {ключ} внутри строки. Неизвестный ключ гасим в пустоту,
// чтобы в готовом документе не осталось висящих фигурных скобок.
function fillTokens(str, data) {
  return String(str).replace(/\{(\w+)\}/g, (_, key) => (data[key] !== undefined ? data[key] : ""));
}

// Текст ячейки ExcelJS: обычная строка, объект richText или формула.
// Нас интересуют только первые два — в бланке токены лежат текстом.
function cellText(value) {
  if (typeof value === "string") return value;
  if (value && Array.isArray(value.richText)) {
    return value.richText.map(r => r.text).join("");
  }
  return null;
}

// ── Геометрия граф бланка ───────────────────────────────────────
//
// ПРОБЛЕМА. Токены расставлены по одиночным ячейкам, а графы бланка шире:
// «Водитель» — это подчёркнутая линия N11:P11, а {driver} лежал в N11
// шириной 6,4 знака, по центру и без объединения. Excel такой текст
// выплёскивает в соседние ячейки в ОБЕ стороны и обрезает о первую занятую —
// то есть ФИО водителя наезжало на подпись «Водитель» слева и упиралось в
// «Вид перевозки» справа. Ровно то же у «Автопредприятия» (E11 при графе
// E11:K11) и у заказчика/отправителя/получателя (E13/E15/E17 при графе E:U).
// Пока в бланке стояли короткие значения, это не бросалось в глаза; с
// реальными названиями ТОО и полным ФИО — полезло.
//
// РЕШЕНИЕ. Каждому токену объявлен диапазон его графы — ровно по нижней
// подчёркивающей рамке бланка (проверено по границам ячеек шаблона).
// Ячейки объединяются, текст прижимается влево и получает shrinkToFit:
// длинное значение ужимается внутри своей графы, а не лезет к соседям.
//
// Диапазоны специфичны для ttn_2026.xlsx, поэтому объединение выполняется
// ТОЛЬКО если в ведущей ячейке действительно стоял ожидаемый токен. Пришлют
// новый бланк с другой раскладкой — раскладка молча не применится, а не
// испортит чужие ячейки.
const FIELD_SPANS = {
  carrier_company: "E11:K11",
  driver: "N11:P11",
  customer: "E13:U13",
  sender: "E15:U15",
  receiver: "E17:U17",
};

// Графы, куда бланк дублирует ФИО водителя, но токена там не оказалось.
//
// В исходном файле заказчика это были формулы: Q43 = O11 («Сдал
// водитель-экспедитор») и G45 = L11 («Принят водитель-экспедитор», подпись
// «ФИО водителя»). При расстановке токенов значение водителя переехало в
// N11, формула Q43 пропала совсем, а G45 осталась смотреть на L11 — а там
// лежит СЛОВО «Водитель», не фамилия. В итоге в графе «ФИО водителя»
// печаталось «Водитель», а «Сдал водитель-экспедитор» уходил пустым.
//
// Формулы не чиним, а заменяем значением: экспорт и так знает ФИО, а
// ExcelJS кэш формул не пересчитывает.
const DRIVER_MIRRORS = { "P43:R43": "driver", "E45:K45": "driver" };

// ── Подписи цепочки в бланке ────────────────────────────────
//
// В бланке ТТН тегов подписи не было вовсе: подпись была одна (получателя) и
// жила только в СМР. Теперь цепочка из четырёх, и три из них в госформе есть
// куда поставить — графы подписей уже нарисованы, не хватало только картинок.
//
// Адреса взяты по подписям самого бланка (проверено по границам ячеек):
//   P44:R44 «подпись» под «Сдал водит.экспедитор»  → водитель
//   T45     линия над «подпись грузополучателя»    → получатель
//   S35     линия «Отпуск разрешил ____»           → клиент (грузоотправитель)
//
// Подписи КЛИЕНТА ПОД ЗАЯВКОЙ в бланке места нет — заявка не перевозочный
// документ, графы под неё в госформе не предусмотрено. Она остаётся в системе
// и видна в карточке; выдумывать ей клетку в госбланке нельзя.
const TTN_SIGNATURES = [
  { anchor: 'P44', role: 'driver' },
  { anchor: 'T45', role: 'receiver' },
  { anchor: 'S35', role: 'client_document' },
];

// Служебный токен-якорь печати. В Excel картинка НЕ привязана к тексту, как
// в docx: она кладётся поверх листа по координатам ячейки. Поэтому в бланке
// стоит токен, экспорт находит его координаты, гасит текст и ставит печать
// в эту позицию — если заказчик пришлёт новую версию бланка, печать переедет
// вместе с якорем, а не останется по забитым координатам.
const STAMP_ANCHOR = "{stamp_here}";

// Печать хранится как data:image/png;base64,… — ExcelJS нужен чистый base64
// и расширение отдельно.
function parseDataUrl(dataUrl) {
  const m = String(dataUrl || "").match(/^data:image\/(png|jpe?g);base64,(.+)$/i);
  if (!m) return null;
  const ext = m[1].toLowerCase() === "png" ? "png" : "jpeg";
  return { ext, base64: m[2] };
}

/**
 * Гашение якоря печати.
 *
 * ПЕЧАТЬ КОМПАНИИ НА ТТН НЕ СТАВИТСЯ — по решению заказчика. Раньше сюда
 * вставлялась картинка из company.stamp; вставку убрали, а гашение токена
 * осталось и убрано быть не может: {stamp_here} — служебная метка, и без
 * очистки она напечаталась бы на бланке буквами. Обход ячеек в fillTtnSheet
 * этот токен намеренно пропускает (единственное исключение), поэтому чистится
 * он только здесь.
 *
 * Сам якорь в бланке оставлен: понадобится вернуть печать — ставить её снова
 * будет некуда, если метку вычистить из шаблона.
 */
function clearStampAnchor(ws) {
  ws.eachRow({ includeEmpty: false }, (row) => {
    row.eachCell({ includeEmpty: false }, (cell) => {
      if (cellText(cell.value) === STAMP_ANCHOR) {
        cell.value = null;
      }
    });
  });
}

// Первая ячейка диапазона вида "E13:U13".
function headOf(range) {
  return String(range).split(":")[0];
}

/**
 * Развернуть графы бланка на всю их ширину.
 *
 * Объединяем только если в ведущей ячейке лежал ожидаемый токен (сравниваем
 * с уже подставленным значением ИЛИ с самим токеном на случай пустого
 * значения). Иначе — молча пропускаем: чужую раскладку ломать нельзя.
 */
function spreadFields(ws, data) {
  Object.entries(FIELD_SPANS).forEach(([key, range]) => {
    const head = ws.getCell(headOf(range));
    const seen = cellText(head.value);
    const expected = data[key];
    // Значение уже подставлено, поэтому ищем его. Пустая графа выглядит как
    // пустая строка — такую тоже разворачиваем: рамка графы должна быть цела.
    if (seen === null || (seen !== expected && seen !== `{${key}}`)) return;
    try {
      ws.mergeCells(range);
    } catch {
      return; // уже объединено — раскладку не трогаем
    }
    const cell = ws.getCell(headOf(range));
    cell.value = expected || "";
    cell.alignment = {
      ...(cell.alignment || {}),
      horizontal: "left",
      vertical: "bottom",
      wrapText: false,
      // Длинное название ТОО ужимается внутри графы, а не выплёскивается
      // на соседние подписи бланка.
      shrinkToFit: true,
    };
  });
}

/**
 * ФИО водителя в графы, где бланк на него ссылался формулой.
 *
 * Формулу заменяем значением: ExcelJS кэш формул не пересчитывает, а старая
 * ссылка (=L11) указывала на ПОДПИСЬ «Водитель», а не на фамилию.
 */
function fillDriverMirrors(ws, data) {
  const driver = String(data.driver || "").trim();
  Object.entries(DRIVER_MIRRORS).forEach(([range, key]) => {
    const head = headOf(range);
    // Гасим всё, что лежало в диапазоне (в т.ч. устаревшие формулы),
    // иначе объединение унесёт мусор в готовый документ.
    const [, endRef] = String(range).split(":");
    const from = ws.getCell(head);
    const to = ws.getCell(endRef);
    for (let c = from.col; c <= to.col; c++) ws.getRow(from.row).getCell(c).value = null;
    try {
      ws.mergeCells(range);
    } catch {
      /* уже объединено — просто пишем значение */
    }
    const cell = ws.getCell(head);
    cell.value = key === "driver" ? driver : String(data[key] || "");
    cell.alignment = { horizontal: "center", vertical: "bottom", shrinkToFit: true };
  });
}

/**
 * Разбивка на страницы: ОДИН лист.
 *
 * ЧТО ПРОСИЛ ЗАКАЗЧИК: «чтобы всё содержимое помещалось на один лист и было
 * читаемо». Два требования тянут в разные стороны, и разводит их арифметика
 * бланка, а не вкус.
 *
 * ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СЖАТЬ ВЕСЬ БЛАНК. Строки 1–67 при печатной ширине
 * A4-альбом требуют масштаба 47,8%. Шрифты бланка 6–11 пт превращаются в
 * 2,9–5,3 пт — это уже не «мелко», это нечитаемо, то есть прямо против
 * второй половины требования.
 *
 * ЧТО НА САМОМ ДЕЛЕ ЗАНИМАЛО ВТОРОЙ ЛИСТ. Строки 48–67 — оборотная сторона
 * бланка: «Погрузочно-разгрузочные операции», «Прочие сведения», «Расчёт
 * стоимости». Там НЕТ НИ ОДНОГО токена: это пустографка, которую от руки
 * заполняет перевозчик. Второй лист уходил заказчику пустым.
 *
 * ЧТО ДЕЛАЕМ: печатаем строки 1–47 — там лежат ВСЕ данные накладной, вплоть
 * до подписей и печати (D47). Им хватает масштаба 70,6% по ширине и 76% по
 * высоте, то есть один лист при читаемом шрифте. Оборот из ФАЙЛА не удалён —
 * он остался на листе ниже области печати: понадобится пустографка — она под
 * рукой, просто не печатается сама собой.
 *
 * ПОЧЕМУ ВЫСОТА ЗАФИКСИРОВАНА. Прежний fitToHeight=0 отдавал высоту на откуп
 * Excel, и автоматический разрыв ложился ПЕРЕД строкой 47 — печать компании
 * ({stamp_here} в D47) уезжала одна на второй лист и отрывалась от блока
 * подписей (строки 43–46). Лицевая сторона уходила заказчику без печати.
 */
function setupPages(ws) {
  // Последняя строка лицевой стороны: в ней печать компании ({stamp_here}, D47).
  const LAST_PRINTED_ROW = 47;

  ws.pageSetup.margins = {
    ...(ws.pageSetup.margins || {}),
    top: 0.4,
    bottom: 0.5,
  };
  // Один лист по обеим осям. fitToPage обязателен: без него Excel печатает
  // по scale и оба fitTo* игнорирует.
  ws.pageSetup.fitToPage = true;
  ws.pageSetup.fitToWidth = 1;
  ws.pageSetup.fitToHeight = 1;
  // Ссылка обязана быть абсолютной ($B$1): относительную строку Excel в имени
  // Print_Area не принимает и молча игнорирует всю область.
  // ExcelJS сам дописывает $ только перед КОЛОНКОЙ, поэтому $ перед строкой
  // ставим здесь — иначе на выходе получается «$B1:$X47», и печатная область
  // не применяется.
  ws.pageSetup.printArea = "B$1:X$47";
  // Ручной разрыв после 47-й строки снят: он делил бланк на лицевую и
  // оборотную стороны, а оборот больше не печатается — разрывать нечего.
  ws.rowBreaks = [];

  // ОБОРОТ НЕ ПЕЧАТАЕМ — И ЭТО ГАРАНТИРУЕТСЯ СКРЫТИЕМ, А НЕ ОБЛАСТЬЮ ПЕЧАТИ.
  //
  // Print_Area — правильный по смыслу инструмент, но живёт он в ОПРЕДЕЛЁННОМ
  // ИМЕНИ КНИГИ, а не на листе. Проверка в Excel показала: у файла, собранного
  // ExcelJS, имя _xlnm.Print_Area в workbook.xml записано верно, а Excel при
  // открытии отдаёт PageSetup.PrintArea пустым. Цена ошибки тут высокая:
  // с fitToHeight=1 и не подхваченной областью Excel ужимает ВЕСЬ лист 1–67
  // до 47,8% — ровно тот нечитаемый вариант, от которого мы уходим.
  //
  // Скрытые строки Excel не печатает никогда и ни при каких настройках.
  // Поэтому область печати оставляем (когда подхватится — хорошо), а
  // единственной опорой делаем скрытие. Данные при этом на месте: строки
  // никуда не делись, «Показать строки» разворачивает пустографку обратно.
  for (let r = LAST_PRINTED_ROW + 1; r <= ws.rowCount; r++) {
    ws.getRow(r).hidden = true;
  }
}

/**
 * Заполнение листа бланка: токены → графы → страницы.
 *
 * Вынесено из exportTtnToXlsx отдельной функцией и без браузерных вызовов:
 * так весь разбор бланка (что куда встало, на скольких листах печатается)
 * проверяется скриптом из Node, а не «на глаз» после выгрузки.
 *
 * @param {object} ws   лист ExcelJS, загруженный из ttn_2026.xlsx
 * @param {object} act  заявка
 * @param {object} [wb] книга — нужна для картинок (печать, подписи).
 *                      Без неё подставляется только текст.
 * @returns {object} подставленные данные (buildTtnData)
 */
export function fillTtnSheet(ws, act, wb) {
  const data = buildTtnData(act);

  // Обходим только ячейки со значениями. Объединённые блоки ExcelJS отдаёт
  // ведущей ячейкой, поэтому писать в «хвост» объединения не пытаемся.
  ws.eachRow({ includeEmpty: false }, (row) => {
    row.eachCell({ includeEmpty: false }, (cell) => {
      const text = cellText(cell.value);
      if (text && text.includes("{") && text !== STAMP_ANCHOR) {
        // Присваиваем плоскую строку: richText с токеном схлопываем,
        // оформление самой ячейки (шрифт, рамки) при этом не трогается.
        cell.value = fillTokens(text, data);
      }
    });
  });

  // Графы разворачиваем ПОСЛЕ подстановки: объединение меняет структуру
  // ячеек, и обход выше на ней бы споткнулся.
  spreadFields(ws, data);
  fillDriverMirrors(ws, data);
  setupPages(ws);

  // Картинки ставятся ПОСЛЕ текста: обход ячеек выше не должен натыкаться на
  // уже обработанный якорь печати.
  // Печать компании на ТТН не ставится (решение заказчика) — только гасим
  // её якорь. Подписи цепочки остаются: у них свои графы (P44/T45/S35) и
  // свой размер, в бланк они укладываются.
  clearStampAnchor(ws);
  if (wb) {
    placeSignatures(wb, ws, act);
  }

  return data;
}

/**
 * Подписи цепочки в бланк.
 *
 * Механика та же, что у печати: Excel не привязывает картинку к тексту, она
 * кладётся поверх листа по координатам ячейки. Подписи нет — ничего не
 * ставим, графа остаётся под ручную роспись.
 *
 * Размер меньше печати (70×30 против 90×75): это роспись от руки, а не оттиск,
 * и она не должна наезжать на соседние графы бланка.
 */
function placeSignatures(wb, ws, act) {
  const list = Array.isArray(act?.signatures) ? act.signatures : [];
  TTN_SIGNATURES.forEach(({ anchor, role }) => {
    const sig = list.filter((s) => s && s.role === role && typeof s.image === 'string').slice(-1)[0];
    const parsed = parseDataUrl(sig?.image);
    if (!parsed) return;
    const cell = ws.getCell(anchor);
    const imgId = wb.addImage({ base64: parsed.base64, extension: parsed.ext });
    ws.addImage(imgId, {
      // ExcelJS считает координаты от нуля, а cell.col/row — от единицы.
      tl: { col: cell.col - 1, row: cell.row - 1 },
      ext: { width: 70, height: 30 },
      editAs: 'oneCell',
    });
  });
}

/**
 * Формирование ТТН.
 *
 * @param {object} act  заявка (с company)
 * @param {object} opts { asBlob: true } — вернуть Blob вместо скачивания.
 *                      Нужно для комплекта документов: там файлы складываются
 *                      в архив, а не сохраняются по одному.
 */
export async function exportTtnToXlsx(act, opts = {}) {
  const needSave = !opts.asBlob;
  const [{ default: ExcelJS }, fileSaver] = await Promise.all([
    import("exceljs"),
    needSave ? import("file-saver") : Promise.resolve(null),
  ]);

  const resp = await fetch("/templates/ttn_2026.xlsx");
  if (!resp.ok) throw new Error("Шаблон ТТН не найден: /templates/ttn_2026.xlsx");
  const buf = await resp.arrayBuffer();

  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(buf);
  const ws = wb.worksheets[0];

  const data = fillTtnSheet(ws, act, wb);

  const out = await wb.xlsx.writeBuffer();
  const blob = new Blob([out], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });
  const filename = `ТТН_${data.number || "новая"}.xlsx`;
  if (!needSave) return { blob, filename };
  fileSaver.saveAs(blob, filename);
  return { blob, filename };
}
