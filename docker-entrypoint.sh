#!/bin/bash
# ============================================================
# Запуск единого контейнера: node (API) + nginx (статика и прокси).
#
# ЗАЧЕМ ДВА ПРОЦЕССА В ОДНОМ КОНТЕЙНЕРЕ. Это сознательный размен. Пока фронт
# и бэк были отдельными сервисами Railway, они деплоились независимо и
# разъезжались по версиям: новый фронт успевал выйти раньше нового бэка и
# звал маршруты, которых там ещё нет. Один образ делает рассинхрон
# невозможным по построению, а не по договорённости о порядке деплоя.
#
# ГЛАВНОЕ ЗДЕСЬ — ПАДАТЬ ЦЕЛИКОМ. Если умрёт node, а nginx останется жив,
# снаружи это выглядит как «сайт открывается, данные не тянутся» — ровно тот
# симптом, из-за которого откатывали прод. Поэтому смерть ЛЮБОГО из двух
# процессов останавливает контейнер, и Railway перезапускает его целиком.
# ============================================================
set -euo pipefail

# Порт снаружи: Railway передаёт его переменной, локально по умолчанию 80.
: "${PORT:=80}"
export PORT

# API слушает свой фиксированный порт и только на петле — наружу он не выходит.
API_PORT=3001

echo "[entrypoint] nginx будет слушать порт ${PORT}, API — ${API_PORT}"

envsubst '${PORT}' < /etc/nginx/templates/app.conf.template > /etc/nginx/conf.d/default.conf
nginx -t

# PORT для node переопределяем: иначе он занял бы порт nginx.
PORT="${API_PORT}" node /app/dist/index.js &
API_PID=$!

# Ждём готовности API, чтобы первые запросы не упирались в 502.
echo "[entrypoint] жду готовности API..."
for _ in $(seq 1 60); do
  if ! kill -0 "${API_PID}" 2>/dev/null; then
    echo "[entrypoint] API упал на старте" >&2
    wait "${API_PID}" || exit $?
    exit 1
  fi
  if curl -fsS "http://127.0.0.1:${API_PORT}/api/health" >/dev/null 2>&1; then
    echo "[entrypoint] API готов"
    break
  fi
  sleep 1
done

nginx -g 'daemon off;' &
NGINX_PID=$!
echo "[entrypoint] nginx запущен"

# wait -n возвращается, как только завершится ЛЮБОЙ из двух.
set +e
wait -n "${API_PID}" "${NGINX_PID}"
CODE=$?
set -e
echo "[entrypoint] один из процессов завершился (код ${CODE}) — останавливаю контейнер" >&2
kill "${API_PID}" "${NGINX_PID}" 2>/dev/null || true
exit "${CODE}"
